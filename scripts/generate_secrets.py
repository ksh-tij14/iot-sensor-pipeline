"""Generate keys and certificates.

Default (live setup) writes, none of it committed (see .gitignore):
  gateway/keystore.local.json    sensor_id -> ECDSA P-256 public key (servers only see these)
  tests/sensor_keys.local.json   private keys of the TEST identities (attack simulator, benchmark)
  docker/certs/local/            TLS certificate + key for the gateway's HTTPS ports
  docker/.env                    gateway HMAC key, event-log key, and the paths above for Docker
  firmware/include/secrets.h     the board's private key and the gateway's pinned TLS key/cert
The physical board's private key is written ONLY to secrets.h; no server file holds it.

--dev writes the committed development material instead (keystore.json,
tests/dev_sensor_keys.json, docker/certs/dev/). Dev keys are public: tests only.

Usage, from the repo root:  python scripts/generate_secrets.py [--device esp32-001] [--dev]
scripts/rotate-keys.ps1 runs this, re-flashes the board and restarts the stack.
"""

import argparse
import datetime
import ipaddress
import json
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from cryptography import x509  # noqa: E402
from cryptography.hazmat.primitives import hashes, serialization  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402
from cryptography.x509.oid import NameOID  # noqa: E402

from shared.crypto_utils import generate_keypair  # noqa: E402
from shared.service_utils import local_ip  # noqa: E402

SENSOR_IDS = ["esp32-001", "esp32-002", "esp32-003"]


def make_certificate(out_dir: Path, ips: list[str]) -> tuple[str, str]:
    """Self-signed EC P-256 certificate for the gateway's TLS ports.
    Returns (certificate PEM, public key PEM). The firmware pins the key."""
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "iot-gateway")])
    sans = [x509.DNSName(n) for n in ("iot-gateway", "gateway-lb", "gateway-2", "localhost")]
    sans += [x509.IPAddress(ipaddress.ip_address(ip)) for ip in dict.fromkeys(ips)]
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - datetime.timedelta(days=1))
            .not_valid_after(now + datetime.timedelta(days=3650))
            .add_extension(x509.SubjectAlternativeName(sans), critical=False)
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    out_dir.mkdir(parents=True, exist_ok=True)
    cert_pem = cert.public_bytes(serialization.Encoding.PEM).decode()
    (out_dir / "server.crt").write_text(cert_pem, encoding="utf-8")
    (out_dir / "server.key").write_bytes(key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    pub_pem = key.public_key().public_bytes(serialization.Encoding.PEM,
                                            serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    return cert_pem, pub_pem


def cert_fingerprint(cert_pem: str) -> str:
    """SHA-1 of the certificate (DER), as aa:bb:.. - what the ESP8266 pins."""
    der_fp = x509.load_pem_x509_certificate(cert_pem.encode()).fingerprint(hashes.SHA1())
    return ":".join(f"{b:02x}" for b in der_fp)


def write_secrets_h(path: Path, private_key: str, cert_pem: str) -> None:
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    ssid = re.search(r'#define WIFI_SSID\s+"([^"]*)"', old)
    pwd = re.search(r'#define WIFI_PASSWORD\s+"([^"]*)"', old)
    path.write_text(f'''// Generated by scripts/generate_secrets.py - gitignored, never commit.
#pragma once

#define WIFI_SSID     "{ssid.group(1) if ssid else "your-wifi-name"}"
#define WIFI_PASSWORD "{pwd.group(1) if pwd else "your-wifi-password"}"

// This board's ECDSA P-256 private key (32 bytes, hex). Only read on first boot
// (or with FORCE_REPROVISION 1), then stored in flash. The gateway knows only
// the matching public key.
#define SENSOR_PRIVATE_KEY "{private_key}"

// The gateway's TLS certificate fingerprint (SHA-1), pinned by the ESP8266: any
// other server is refused. (The ESP8266 core's public-key pinning rejects valid
// ECDSA handshakes, so the certificate is pinned instead.)
#define GATEWAY_TLS_FINGERPRINT "{cert_fingerprint(cert_pem)}"

// The gateway's TLS certificate, used by the ESP32 build to verify the server.
static const char GATEWAY_TLS_CERT[] PROGMEM = R"PEM(
{cert_pem.strip()}
)PEM";
''', encoding="utf-8")


def read_env(path: Path) -> dict:
    """KEY=value pairs from an existing .env file ({} if there isn't one)."""
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return {}
    return dict(line.split("=", 1) for line in lines if "=" in line and not line.lstrip().startswith("#"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--device", default="esp32-001", help="sensor_id of the physical board")
    parser.add_argument("--dev", action="store_true", help="write the committed dev keys instead")
    parser.add_argument("--new-log-key", action="store_true",
                        help="also replace the event-log key (entries sealed with the old key can then "
                             "no longer be verified; archive the log first)")
    args = parser.parse_args()

    pairs = {sid: generate_keypair() for sid in SENSOR_IDS}            # sid -> (private, public)
    keystore = {sid: {"public_key": pub, "revoked": False} for sid, (_, pub) in pairs.items()}
    ips = ["127.0.0.1", local_ip()]

    if args.dev:
        (ROOT / "gateway" / "keystore.json").write_text(json.dumps(keystore, indent=2) + "\n", encoding="utf-8")
        (ROOT / "tests" / "dev_sensor_keys.json").write_text(
            json.dumps({sid: priv for sid, (priv, _) in pairs.items()}, indent=2) + "\n", encoding="utf-8")
        make_certificate(ROOT / "docker" / "certs" / "dev", ips)
        print("Dev keys written (public, for tests only).")
        return

    (ROOT / "gateway" / "keystore.local.json").write_text(json.dumps(keystore, indent=2) + "\n", encoding="utf-8")
    test_keys = {sid: priv for sid, (priv, _) in pairs.items() if sid != args.device}
    (ROOT / "tests" / "sensor_keys.local.json").write_text(json.dumps(test_keys, indent=2) + "\n", encoding="utf-8")
    cert_pem, _ = make_certificate(ROOT / "docker" / "certs" / "local", ips)
    # Rotating device keys must not orphan the event log: keep its key unless asked.
    log_key = None if args.new_log_key else read_env(ROOT / "docker" / ".env").get("EVENT_LOG_KEY")
    (ROOT / "docker" / ".env").write_text(
        "# Generated by scripts/generate_secrets.py - do not commit.\n"
        f"GATEWAY_SECRET={secrets.token_hex(32)}\n"
        f"EVENT_LOG_KEY={log_key or secrets.token_hex(32)}\n"
        "KEYSTORE_FILE=../gateway/keystore.local.json\n"
        "SENSOR_KEYS_FILE=../tests/sensor_keys.local.json\n"
        "CERT_DIR=./certs/local\n", encoding="utf-8")
    write_secrets_h(ROOT / "firmware" / "include" / "secrets.h", pairs[args.device][0], cert_pem)

    print(f"New ECDSA keys for {len(SENSOR_IDS)} sensors (public keys -> gateway/keystore.local.json)")
    print(f"Board {args.device}'s private key -> firmware/include/secrets.h only")
    print(f"TLS certificate for {', '.join(dict.fromkeys(ips))} -> docker/certs/local/")
    print("Gateway key (new) + event-log key (" + ("kept" if log_key else "new") + ") -> docker/.env")


if __name__ == "__main__":
    main()
